db.employees.aggregate([
    {
        $group:{
            _id:"$departamento",
            salario_promedio:{$avg:"$salario"}
        }
    },
    {
        $lookup:{
            from:"employees",
            localField:"_id",
            foreignField:"departamento",
            as:"empleados"
        }
    },
    { $unwind: "$empleados" },   
    {
        $addFields:{
            diferencia:{
                $subtract:["$empleados.salario","$salario_promedio"]
            }
        }  
    }
])
